/** 12345 or 12345-6789. Puerto Rico ZIPs keep their leading zeros (00901). */
export const ZIP_PATTERN = /^\d{5}(-\d{4})?$/;

/** Puerto Rico ships as US domestic mail; the country is only for the packing slip. */
export const countryForState = (code: string) => (code === 'PR' ? 'Puerto Rico' : 'United States');
